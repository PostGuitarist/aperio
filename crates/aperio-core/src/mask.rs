use serde::{Deserialize, Serialize};

/// Limits where a layer's operations apply. Coordinates are normalized to the
/// uncropped source image, so masks survive crop changes.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Mask {
    /// Painted strokes, replayed in order.
    Brush { strokes: Vec<BrushStroke> },
    /// Linear gradient from fully applied at `start` to not applied at `end`.
    Linear { start: [f32; 2], end: [f32; 2] },
    /// Elliptical gradient with a soft edge.
    Radial {
        center: [f32; 2],
        radius: [f32; 2],
        angle_deg: f32,
        feather: f32,
        invert: bool,
    },
    /// Selects pixels by brightness: fully on between `low` and `high`
    /// (sRGB-encoded luminance, 0.0 to 1.0), fading out over `feather` on
    /// either side. Read from the photo before any layer's adjustments.
    Luminance {
        low: f32,
        high: f32,
        #[serde(default = "default_feather")]
        feather: f32,
    },
    /// Selects pixels by hue: fully on within `range` degrees of `hue`,
    /// fading out over `feather` more degrees. Grays are never selected.
    /// Read from the photo before any layer's adjustments.
    Color {
        hue: f32,
        #[serde(default = "default_hue_range")]
        range: f32,
        #[serde(default = "default_hue_feather")]
        feather: f32,
    },
    /// Several masks combined in order. The first part's mode is ignored;
    /// each later part is added to, subtracted from, or intersected with
    /// the result so far.
    Combine { parts: Vec<MaskPart> },
    /// A mask generated by a plugin, such as AI sky or subject segmentation.
    /// The result is cached outside the sidecar and regenerated when missing.
    Plugin {
        plugin: String,
        version: String,
        params: serde_json::Value,
    },
}

/// One mask of [`Mask::Combine`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MaskPart {
    #[serde(default)]
    pub mode: MaskMode,
    /// Use the opposite of this part's mask.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub invert: bool,
    pub mask: Mask,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MaskMode {
    #[default]
    Add,
    Subtract,
    Intersect,
}

fn default_feather() -> f32 {
    0.1
}

fn default_hue_range() -> f32 {
    20.0
}

fn default_hue_feather() -> f32 {
    20.0
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BrushStroke {
    pub points: Vec<[f32; 2]>,
    pub size: f32,
    pub feather: f32,
    pub flow: f32,
    /// True when the stroke removes from the mask instead of adding to it.
    pub erase: bool,
}
