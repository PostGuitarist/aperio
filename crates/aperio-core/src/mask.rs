use serde::{Deserialize, Serialize};

/// Limits where a layer's operations apply. Coordinates are normalized to the
/// uncropped source image, so masks survive crop changes.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Mask {
    /// Painted strokes, replayed in order.
    Brush { strokes: Vec<BrushStroke> },
    /// Linear gradient from fully applied at `start` to not applied at `end`.
    Linear { start: [f32; 2], end: [f32; 2] },
    /// Elliptical gradient with a soft edge.
    Radial {
        center: [f32; 2],
        radius: [f32; 2],
        angle_deg: f32,
        feather: f32,
        invert: bool,
    },
    /// A mask generated by a plugin, such as AI sky or subject segmentation.
    /// The result is cached outside the sidecar and regenerated when missing.
    Plugin {
        plugin: String,
        version: String,
        params: serde_json::Value,
    },
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BrushStroke {
    pub points: Vec<[f32; 2]>,
    pub size: f32,
    pub feather: f32,
    pub flow: f32,
    /// True when the stroke removes from the mask instead of adding to it.
    pub erase: bool,
}
